/**
 * Step 06: reviewed Arabic hints for the most frequent library words
 * (DECISIONS OD4, OD11). The hints are written for this project in batches,
 * scripts/content/hints/batch-NN.json, and reviewed before they are added.
 *
 * Validation (the step fails on any problem, so a bad batch never ships):
 * - Arabic letters, no Latin letters (RTL readability), at most 60 characters,
 *   no leading or trailing spaces and no empty alternatives (" / / ");
 * - the word is a library word (not a bank word: those keep their own hint);
 * - a word appears in one batch only.
 * The report lists the top-TOP words that still lack a hint; the content test
 * requires none.
 *
 * Output: content-raw/work/hints.json (merged into the word chunks by step 09).
 */
import { readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { readJson, runStep, writeJson } from "./lib/checkpoint.mjs";
import { PIPELINE, WORK } from "./lib/paths.mjs";
import { WORDS } from "./04-words.mjs";

const SCRIPT = fileURLToPath(import.meta.url);
const DIR = join(PIPELINE, "hints");
export const HINTS_OUT = join(WORK, "hints.json");
export const TOP = 3000;

/** Problems with one hint, or [] when it is fine. */
export function hintProblems(text) {
  const out = [];
  if (typeof text !== "string" || text.length === 0) return ["empty"];
  if (!/[؀-ۿ]/.test(text)) out.push("no Arabic letters");
  if (/[A-Za-z]/.test(text)) out.push("Latin letters");
  if (text.length > 60) out.push("longer than 60 characters");
  if (text !== text.trim() || /\s{2,}/.test(text)) out.push("stray spaces");
  if (/(^|\/)\s*(\/|$)/.test(text)) out.push("empty alternative");
  return out;
}

export async function run({ force = false } = {}) {
  const files = readdirSync(DIR).filter((f) => /^batch-\d{2}\.json$/.test(f)).sort().map((f) => join(DIR, f));
  const { result } = await runStep(WORK, "hints", { script: SCRIPT, inputs: [...files, WORDS], outputs: [HINTS_OUT], options: { TOP }, force }, async () => {
    const { words } = readJson(WORDS);
    const library = new Set(words.map((w) => w.word));
    const hints = {};
    const from = {};
    const problems = [];
    for (const f of files) {
      const name = f.split(/[\\/]/).pop();
      for (const [word, text] of Object.entries(readJson(f).hints)) {
        if (from[word]) problems.push(`${word}: in ${from[word]} and ${name}`);
        if (!library.has(word)) problems.push(`${word} (${name}): not a library word`);
        for (const p of hintProblems(text)) problems.push(`${word} (${name}): ${p}`);
        hints[word] = text;
        from[word] = name;
      }
    }
    if (problems.length) throw new Error(`hint problems:\n${problems.join("\n")}`);
    const missing = words.filter((w) => w.rank <= TOP && !hints[w.word]).sort((a, b) => a.rank - b.rank).map((w) => w.word);
    writeJson(HINTS_OUT, { $comment: "Merged reviewed hints. Generated by 06-hints.mjs.", hints, missing });
    return { batches: files.length, hints: Object.keys(hints).length, missingTop: missing.length };
  });
  return result;
}

/**
 * Step 07: the licence notices the sources ask us to reproduce in our
 * documentation (DECISIONS OD1), copied word for word into
 * src/data/credits/notices.generated.ts, which only the /credits page imports.
 *
 * - SCOWL: the whole `Copyright` file (it also carries the Ispell, WordNet 1.6
 *   and public-domain notices of its parts).
 * - VarCon: the "Copyright" section of its README (Kevin Atkinson, Benjamin
 *   Titze and the Ispell licence).
 * - CMU Pronouncing Dictionary: its LICENSE file.
 * - dictionary-en: its licence file (MIT and the SCOWL notice).
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { runStep, writeAtomic } from "./lib/checkpoint.mjs";
import { DOWNLOADS, EXTRACTED, ROOT, WORK } from "./lib/paths.mjs";

const SCRIPT = fileURLToPath(import.meta.url);
const SCOWL = join(EXTRACTED, "scowl", "scowl", "scowl-2020.12.07", "Copyright");
const VARCON = join(EXTRACTED, "varcon", "varcon", "varcon-2020.12.07", "README");
const CMU = join(DOWNLOADS, "cmudict", "LICENSE");
const DICT = join(ROOT, "node_modules", "dictionary-en", "license");
export const NOTICES_OUT = join(ROOT, "src", "data", "credits", "notices.generated.ts");

const clean = (s) => s.replace(/\r\n/g, "\n").replace(/[ \t]+$/gm, "").trim();

export function varconNotice(readme) {
  const text = clean(readme);
  const start = text.search(/^Copyright\n=+$/m);
  if (start < 0) throw new Error("VarCon README: no Copyright section");
  return text.slice(start).replace(/^Copyright\n=+\n+/, "");
}

export async function run({ force = false } = {}) {
  const { result } = await runStep(WORK, "notices", { script: SCRIPT, inputs: [SCOWL, VARCON, CMU, DICT], outputs: [NOTICES_OUT], force }, async () => {
    const notices = {
      scowl: clean(readFileSync(SCOWL, "latin1")),
      varcon: varconNotice(readFileSync(VARCON, "latin1")),
      cmudict: clean(readFileSync(CMU, "utf8")),
      dictionaryEn: clean(readFileSync(DICT, "utf8")),
    };
    const body = Object.entries(notices)
      .map(([k, v]) => `export const ${k.toUpperCase().replace("DICTIONARYEN", "DICTIONARY_EN")}_NOTICE = ${JSON.stringify(v)};`)
      .join("\n\n");
    writeAtomic(
      NOTICES_OUT,
      `// Generated by scripts/content/07-notices.mjs from the pinned sources. Do not edit by hand.\n// Licence notices reproduced word for word, as the sources require (DECISIONS OD1).\n\n${body}\n`,
    );
    return Object.fromEntries(Object.entries(notices).map(([k, v]) => [k, v.length]));
  });
  return result;
}

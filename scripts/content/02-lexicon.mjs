/**
 * Step 02: the candidate lexicon.
 *
 * Candidates are the SCOWL 2020.12.07 English and American word lists of sizes
 * 10–60 (sizes above 60 are never read: the UKACD terms start above 80). Each
 * candidate keeps its smallest size as a commonness tier. A candidate is kept
 * only when it is lower-case letters (inner hyphens allowed), at least two
 * letters long, accepted by dictionary-en (the same dictionary the browser
 * uses) and not on any taboo or sensitive list. Every rejection is counted.
 *
 * Output: content-raw/work/lexicon.json (git-ignored).
 */
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { runStep, writeJson } from "./lib/checkpoint.mjs";
import { EXTRACTED, PIPELINE, WORK } from "./lib/paths.mjs";
import { loadBlocklist, noSuggestWords, readLatin1Lines, spellChecker } from "./lib/text.mjs";

const SCRIPT = fileURLToPath(import.meta.url);
export const SCOWL_DIR = join(EXTRACTED, "scowl", "scowl", "scowl-2020.12.07");
export const SIZES = [10, 20, 35, 40, 50, 55, 60];
export const LEXICON = join(WORK, "lexicon.json");
const WORD_RE = /^[a-z]+(?:-[a-z]+)*$/;

function listFiles(kind) {
  const dir = join(SCOWL_DIR, "final");
  return readdirSync(dir).filter((f) => {
    const m = /^(english|american)-([a-z-]+)\.(\d+)$/.exec(f);
    return m && m[2] === kind && Number(m[3]) <= 60;
  });
}

export async function run({ force = false } = {}) {
  const final = join(SCOWL_DIR, "final");
  if (!existsSync(final)) throw new Error("SCOWL is not extracted: run the fetch step first");
  const wordFiles = listFiles("words").map((f) => join(final, f));
  const filterFiles = ["abbreviations", "proper-names", "upper", "contractions"].flatMap(listFiles).map((f) => join(final, f));
  const taboo = ["offensive.1", "offensive.2", "profane.1", "profane.3"].map((f) => join(SCOWL_DIR, "misc", f));
  const inputs = [...wordFiles, ...filterFiles, ...taboo, join(PIPELINE, "blocklist.json")];

  const { result } = await runStep(WORK, "lexicon", { script: SCRIPT, inputs, outputs: [LEXICON], force }, async () => {
    const tier = new Map();
    for (const f of wordFiles) {
      const size = Number(f.split(".").pop());
      for (const w of readLatin1Lines(f)) if (!tier.has(w) || tier.get(w) > size) tier.set(w, size);
    }
    const abbreviations = new Set(filterFiles.filter((f) => f.includes("abbreviations")).flatMap(readLatin1Lines).map((w) => w.toLowerCase()));
    const tabooSet = new Set(taboo.flatMap(readLatin1Lines).map((w) => w.toLowerCase()));
    const noSuggest = noSuggestWords();
    const { words: blocked } = loadBlocklist();
    const spell = spellChecker();

    const rejected = {};
    const reject = (reason, w) => {
      const r = (rejected[reason] ??= { count: 0, samples: [] });
      r.count++;
      if (r.samples.length < 12) r.samples.push(w);
    };
    const kept = [];
    for (const [w, size] of tier) {
      if (!WORD_RE.test(w)) reject(/'s$/.test(w) ? "possessive" : /^[A-Z]/.test(w) ? "capitalised" : "not plain letters", w);
      else if (w.length < 2) reject("single letter", w);
      else if (tabooSet.has(w) || noSuggest.has(w)) reject("taboo (SCOWL misc lists, NOSUGGEST)", w);
      else if (blocked.has(w)) reject(`sensitive (${blocked.get(w)})`, w);
      else if (abbreviations.has(w)) reject("abbreviation", w);
      else if (!spell.correct(w)) reject("not in dictionary-en", w);
      else kept.push([w, size]);
    }
    kept.sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]));
    writeJson(LEXICON, { $comment: "Candidate lexicon: [word, SCOWL size]. Generated by 02-lexicon.mjs.", words: kept, rejected });
    return { candidates: tier.size, kept: kept.length, rejected: Object.fromEntries(Object.entries(rejected).map(([k, v]) => [k, v.count])) };
  });
  return result;
}

/**
 * Step 03: English word frequencies from the Tatoeba English sentences
 * (CC BY 2.0 FR). Only counts are derived here; no sentence text is kept.
 *
 * Tokens are counted case-sensitively. A capitalised token at the start of a
 * sentence counts for the lower-case word only when that word is mostly written
 * in lower case in the middle of sentences, so "The" counts for "the" but "Tom"
 * does not count for "tom".
 *
 * Output: content-raw/work/frequency.json (git-ignored).
 */
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { runStep, writeJson } from "./lib/checkpoint.mjs";
import { EXTRACTED, WORK } from "./lib/paths.mjs";
import { lines, wordTokens } from "./lib/text.mjs";

const SCRIPT = fileURLToPath(import.meta.url);
export const ENG = join(EXTRACTED, "tatoeba", "eng_sentences_detailed.tsv");
export const FREQUENCY = join(WORK, "frequency.json");

export async function run({ force = false } = {}) {
  const { result } = await runStep(WORK, "frequency", { script: SCRIPT, inputs: [ENG], outputs: [FREQUENCY], force }, async () => {
    const lower = new Map();
    const upperMid = new Map();
    const initial = new Map();
    const inc = (m, k) => m.set(k, (m.get(k) ?? 0) + 1);
    let sentences = 0;
    for await (const line of lines(ENG)) {
      const text = line.split("\t")[2];
      if (!text) continue;
      sentences++;
      const tokens = wordTokens(text.replace(/’/g, "'"));
      tokens.forEach((t, i) => {
        if (t === t.toLowerCase()) inc(lower, t);
        else if (i === 0 && t.slice(1) === t.slice(1).toLowerCase()) inc(initial, t.toLowerCase());
        else if (t.slice(1) === t.slice(1).toLowerCase()) inc(upperMid, t.toLowerCase());
      });
    }
    const counts = {};
    for (const [w, n] of lower) {
      const total = n + (n >= (upperMid.get(w) ?? 0) ? (initial.get(w) ?? 0) : 0);
      if (total >= 2) counts[w] = total;
    }
    writeJson(FREQUENCY, { $comment: "Token counts over the Tatoeba English export pinned in sources.lock.json. Generated by 03-frequency.mjs.", sentences, counts });
    return { sentences, types: Object.keys(counts).length };
  });
  return result;
}
